package com.ibatulanand.orderservice.service;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.ibatulanand.orderservice.dto.OrderTotals;
import com.ibatulanand.orderservice.dto.ProductResponse;
import com.ibatulanand.orderservice.model.Promotion;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import java.io.InputStream;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

class PricingServiceTest {

    private static final BigDecimal TAX_RATE = new BigDecimal("0.08625");
    private final PricingService pricing = new PricingService(null, null, null);
    private final List<ProductResponse> products = loadProducts();

    @Test
    void goldenCartMatchesPre1Numbers() {
        OrderTotals t = price(new int[]{1, 1, 1}, List.of("FALL30"), "12.00", false).totals();
        assertThat(t.getMerchandiseTotal()).isEqualByComparingTo("159.85");
        assertThat(t.getDiscountTotal()).isEqualByComparingTo("63.54");
        assertThat(t.getTaxableSubtotal()).isEqualByComparingTo("108.31");
        assertThat(t.getSalesTax()).isEqualByComparingTo("9.34");
        assertThat(t.getTotal()).isEqualByComparingTo("117.65");
    }

    @Test
    void goldenCartTaxExemptIs10831() {
        OrderTotals t = price(new int[]{1, 1, 1}, List.of("FALL30"), "12.00", true).totals();
        assertThat(t.getSalesTax()).isEqualByComparingTo("0.00");
        assertThat(t.getTotal()).isEqualByComparingTo("108.31");
        assertThat(t.isTaxExempt()).isTrue();
    }

    @Test
    void promotionAllocationsSkipFinalSaleAndSumExactlyToOrderTotal() {
        PricingService.PricingResult result = price(new int[]{1, 1, 1}, List.of("FALL30", "CARD10"), "12.00", false);
        for (Map.Entry<String, BigDecimal> promo : result.promotionTotals().entrySet()) {
            BigDecimal allocated = result.lines().stream()
                    .map(l -> l.promotionAllocations().getOrDefault(promo.getKey(), BigDecimal.ZERO))
                    .reduce(BigDecimal.ZERO, BigDecimal::add);
            assertThat(allocated).isEqualByComparingTo(promo.getValue());
        }
        PricingService.PricedLine finalSaleLine = result.lines().get(0);
        assertThat(finalSaleLine.product().getSkuCode()).isEqualTo("268341-016-L");
        assertThat(finalSaleLine.promotionAmount()).isEqualByComparingTo("0.00");
    }

    /** Expected values generated by running pos-webapp/src/lib/totals.ts#calculateTotals on the same carts. */
    @ParameterizedTest
    @CsvSource({
            "1;1;1, FALL30,        12.00, false, 159.85, 63.54,  108.31, 9.34,  117.65",
            "1;1;1, FALL30,        12.00, true,  159.85, 63.54,  108.31, 0.00,  108.31",
            "1;1;1, FALL30|CARD10, 12.00, false, 159.85, 74.73,  97.12,  8.38,  105.50",
            "2;3;1, CARD10,        0.00,  false, 329.70, 67.12,  262.58, 22.65, 285.23",
            "0;1;0, '',            5.50,  false, 69.95,  0.00,   75.45,  6.51,  81.96",
            "3;0;2, FALL30,        12.00, false, 209.75, 97.08,  124.67, 10.75, 135.42",
            "1;0;0, FALL30,        0.00,  false, 29.95,  11.98,  17.97,  1.55,  19.52",
            "0;7;5, FALL30|CARD10, 24.99, false, 789.40, 369.70, 444.69, 38.35, 483.04"
    })
    void matchesTotalsTsRounding(String qty, String promos, String services, boolean exempt,
                                 String merchandise, String discount, String taxable, String tax, String total) {
        int[] q = Arrays.stream(qty.split(";")).mapToInt(Integer::parseInt).toArray();
        List<String> codes = promos.isBlank() ? List.of() : List.of(promos.split("\\|"));
        OrderTotals t = price(q, codes, services, exempt).totals();
        assertThat(t.getMerchandiseTotal()).isEqualByComparingTo(merchandise);
        assertThat(t.getDiscountTotal()).isEqualByComparingTo(discount);
        assertThat(t.getTaxableSubtotal()).isEqualByComparingTo(taxable);
        assertThat(t.getSalesTax()).isEqualByComparingTo(tax);
        assertThat(t.getTotal()).isEqualByComparingTo(total);
    }

    private PricingService.PricingResult price(int[] quantities, List<String> codes, String services, boolean exempt) {
        List<PricingService.PricedLineInput> inputs = new ArrayList<>();
        for (int i = 0; i < quantities.length; i++) {
            if (quantities[i] > 0) {
                inputs.add(new PricingService.PricedLineInput(products.get(i), quantities[i]));
            }
        }
        List<Promotion> promotions = codes.stream().map(PricingServiceTest::promotion).toList();
        return pricing.price(inputs, promotions, new BigDecimal(services), exempt, TAX_RATE);
    }

    private static Promotion promotion(String code) {
        Promotion p = new Promotion();
        p.setCode(code);
        p.setPercentOff(new BigDecimal("FALL30".equals(code) ? "30" : "10"));
        p.setAmountOff(BigDecimal.ZERO);
        p.setActive(true);
        return p;
    }

    private static List<ProductResponse> loadProducts() {
        try (InputStream in = PricingServiceTest.class.getResourceAsStream("/fixtures/products.json")) {
            return new ObjectMapper().readValue(in, new TypeReference<>() { });
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }
}
